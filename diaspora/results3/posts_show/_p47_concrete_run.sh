#!/bin/bash
# P47 variant of _concrete_run.sh. IDENTICAL except for ONE thing:
#
#   it takes its JRuby slot from the P47-PRIVATE namespace (_p47_slot.sh,
#   /tmp/p47-concolic-slot-N.lock) instead of the SHARED one
#   (reports/diaspora/tools/slot, /tmp/concolic-slot-N.lock).
#
# WHY. `tools/slot` searches slots 1..$CONCOLIC_SLOTS and has no notion of
# reservation -- N is a SEARCH RANGE. The conversations_index full gate is
# running with CONCOLIC_SLOTS=3 and holds shared slots 1-3; a bare
# _concrete_run.sh (which sets no CONCOLIC_SLOTS at all, so N defaults to 2)
# would search exactly slots 1 and 2 and STEAL one from the protected gate the
# moment it fell free between probe batches. That is the 2026-09-25 04:20
# incident, verbatim -- see _p47_slot.sh and the handoff section 2.
#
# The concrete round is SERIAL (one manifest at a time), so P47_SLOTS=1 is
# sufficient and is what the launcher should set.
#
# SECOND DIFFERENCE, added 2026-09-25 21:10: it runs `_p48_concrete_run_probe.rb`
# (generated by `_p48_mk_probe.py`) instead of the shared
# `tools/concrete_checker/concrete_run_probe.rb`, because the shared one dies at
# load for EVERY endpoint since src commit 1d74415 (2026-09-20):
#
#   LoadError: no such file to load --
#     .../tools/concrete_checker/target_call_probe
#
# That commit moved the probe out of src/ and deliberately left
# target_call_probe.rb behind, but did not update the probe's
# `require_relative "target_call_probe"`. The shared file is LEFT UNTOUCHED
# pending a decision; the generator re-derives the local copy from it and
# refuses if the anchor stops matching (i.e. if it gets fixed upstream).
set +e; unset JAVA_TOOL_OPTIONS; cd /home/dev/project
B=/home/dev/project/reports/diaspora/results3/posts_show
LOG="$B/_p47_concrete_run.log"; : > "$LOG"
say(){ echo "[$(date -Is)] $*" | tee -a "$LOG"; }
for M in anon_html anon_nonpublic anon_json auth_html auth_json; do
  say "=== manifest $M ==="
  rm -f "$B/concrete_run.json"
  "$B/_p47_slot.sh" env JRUBY_OPTS=--debug CONCRETE_COVERAGE=1 \
    /home/dev/project/scripts/diaspora-concolic \
    "$B/_p48_concrete_run_probe.rb" \
    "$B/concrete_manifest_${M}.rb" >> "$LOG" 2>&1
  rc=$?
  if [ -f "$B/concrete_run.json" ]; then
    mv "$B/concrete_run.json" "$B/concrete_run_${M}.json"
    say "$M rc=$rc -> concrete_run_${M}.json"
  else
    say "$M rc=$rc -> NO OUTPUT (JVM abort or load failure) — NOT silently skipped"
  fi
done
python3 - "$B" <<'PY' | tee -a "$LOG"
import glob, json, os, sys
B = sys.argv[1]
merged = []
for f in sorted(glob.glob(os.path.join(B, "concrete_run_*.json"))):
    for sc in json.load(open(f)):
        if sc["name"] == "_cumulative_coverage" and any(
                m["name"] == "_cumulative_coverage" for m in merged):
            # keep ONE cumulative-coverage entry, unioned
            tgt = next(m for m in merged if m["name"] == "_cumulative_coverage")
            for k, v in sc["coverage"].items():
                tgt["coverage"][k] = sorted(set(tgt["coverage"].get(k, [])) | set(v))
            continue
        merged.append(sc)
json.dump(merged, open(os.path.join(B, "concrete_run.json"), "w"), indent=1)
for m in merged:
    print("%-30s target_calls=%-5d statements=%-4d error=%s" % (
        m["name"], len(m.get("target_calls") or []),
        len(m.get("statements") or []), m.get("error")))
print("merged -> concrete_run.json (%d scenarios)" % len(merged))
PY
say "=== CONCRETE ROUND END ==="
