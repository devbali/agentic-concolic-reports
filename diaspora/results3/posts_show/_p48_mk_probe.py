#!/usr/bin/env python3
"""Regenerate `_p48_concrete_run_probe.rb` from the SHARED concrete_run_probe.rb,
applying exactly one substitution: the broken `require_relative`.

    usage: _p48_mk_probe.py [--check]

THE DEFECT (shared tooling, not this batch).

`reports/diaspora/tools/concrete_checker/concrete_run_probe.rb:46` says

    require_relative "target_call_probe"

but `target_call_probe.rb` is NOT in that directory. It is in
`src/ruby_runtime/completion_checker/target_call_probe.rb`.

HOW IT GOT THAT WAY. Until src commit `1d74415` ("Move the concrete-checker
tooling out of src/ into reports/diaspora/", 2026-09-20 19:30) the probe lived
in `src/ruby_runtime/completion_checker/`, RIGHT NEXT TO `target_call_probe.rb`,
and the `require_relative` resolved correctly. That commit moved the probe out
and deliberately left `target_call_probe.rb` behind -- its own README calls that
file "genuinely core, required by every probe" -- but did not update the
`require_relative`. Verified against `git -C src show 1d74415^:...` : the line
is byte-identical before and after the move.

The README even states the correct dependency in prose:

    "Requires src/ruby_runtime/completion_checker/target_call_probe.rb
     (still in src/ -- genuinely core, required by every probe)."

so the documentation and the code disagree, and the code is the wrong one.

BLAST RADIUS. `concrete_run_probe.rb` dies at load for EVERY endpoint, on every
invocation, since 2026-09-20:

    LoadError: no such file to load --
      /home/dev/project/reports/diaspora/tools/concrete_checker/target_call_probe

posts_show did not notice because its shipped `concrete_run.json` was generated
2026-09-10, ten days BEFORE the move.

WHY THIS SCRIPT INSTEAD OF FIXING THE SHARED FILE. The shared fix is one line
(or a symlink) and is obviously correct, but `tools/` is shared across every
endpoint and the standing rule for this session is to FLAG a shared change and
let the coordinator decide, not to land it unilaterally. So this batch gets a
LOCAL copy and the shared file is left exactly as it is.

WHY A GENERATOR AND NOT A CHECKED-IN COPY. A stale fork of a shared tool is its
own silent defect -- the whole point of the bug above. This regenerates the
local copy FROM the shared original every time, applies exactly ONE textual
substitution, and REFUSES if the anchor does not match exactly once. So:
  * any future change to the shared probe is inherited on the next regeneration;
  * if the shared file is fixed upstream, the anchor stops matching and this
    script says so loudly instead of silently shadowing the fix.

Lines 90 and 162 of the probe resolve against the MANIFEST path
(`File.expand_path(manifest)`), not against the probe's own location, so moving
the probe does not move `concrete_run.json` -- it still lands beside the
manifest, i.e. in this batch directory. That was checked, not assumed.
"""
import argparse
import hashlib
import os
import sys

B = '/home/dev/project/reports/diaspora/results3/posts_show'
SHARED = '/home/dev/project/reports/diaspora/tools/concrete_checker/concrete_run_probe.rb'
PROBE = '/home/dev/project/src/ruby_runtime/completion_checker/target_call_probe.rb'
OUT = os.path.join(B, '_p48_concrete_run_probe.rb')

ANCHOR = 'require_relative "target_call_probe"'
REPL = 'require %s  # _p48: was `require_relative "target_call_probe"`, which resolves\n' % (
    '"%s"' % PROBE.replace('.rb', ''))
REPL += '# into tools/concrete_checker/ where that file does not exist. See _p48_mk_probe.py.'

BANNER = """# GENERATED by _p48_mk_probe.py -- DO NOT EDIT BY HAND.
# Source: reports/diaspora/tools/concrete_checker/concrete_run_probe.rb
# Source sha256: %s
# One substitution only: the `require_relative "target_call_probe"` on the line
# below, which has been broken for every endpoint since src commit 1d74415
# (2026-09-20) moved this probe out of src/ and left target_call_probe.rb there.
# Regenerate with: python3 %s
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true',
                    help='verify the local copy is current; do not write')
    a = ap.parse_args()

    if not os.path.exists(PROBE):
        sys.exit(f'REFUSING: {PROBE} does not exist -- the substitution would '
                 f'produce a probe that is broken a different way')
    src = open(SHARED).read()

    n = src.count(ANCHOR)
    if n != 1:
        sys.exit(f'REFUSING: anchor matched {n} times in {SHARED} (expected 1). '
                 f'If it matched 0, the shared file may have been FIXED upstream '
                 f'-- delete {os.path.basename(OUT)} and use the shared probe.')

    sha = hashlib.sha256(src.encode()).hexdigest()[:16]
    out = BANNER % (sha, __file__) + src.replace(ANCHOR, REPL, 1)

    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else None
        if cur == out:
            print(f'current: {os.path.basename(OUT)} matches shared sha256 {sha}')
            return
        sys.exit(f'STALE: {os.path.basename(OUT)} does not match the shared probe '
                 f'(sha256 {sha}); regenerate')

    open(OUT, 'w').write(out)
    print(f'wrote {OUT}')
    print(f'  from  {SHARED} (sha256 {sha})')
    print(f'  require -> {PROBE}')


if __name__ == '__main__':
    main()
