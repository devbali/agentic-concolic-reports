#!/usr/bin/env python3
"""Native per-clique enumeration of people_show missing combos.

Bali directive 2026-09-04 05:19 (CRITICAL correction): the earlier per-item
script reimplemented the query path and authored PARSE FAILURE as "UNSAT".
This script does NOT reimplement the solver path. It drives the checker's
NATIVE machinery, one maximal clique at a time, so every combo + its z3 model
comes from coverage.py's own `_next_untried_combo` / `check_satisfiability`
(with `_Z3_NAMESPACE` eval), exactly as the bounded run did — but with the
per-clique cap raised (max_missing_per_clique) and a per-clique wall-clock
budget so we never trigger the all-at-once enumeration explosion.

Per-clique algorithm (mirrors CoverageChecker.check_coverage steps 1-6 but
parameterized per clique, and checkpointed after every clique):
  1. Load the same runs + assumptions the bounded run used (4984 corpus).
  2. Reuse the checker's own steps: universe, decls/bounds/fixed_base,
     parseability (tautology) probe, assumption filtering, dependence graph,
     maximal cliques.
  3. For each clique (one at a time, <= PER_CLIQUE_BUDGET seconds): enumerate
     SAT combos by calling the checker's NATIVE `_next_untried_combo`, raising
     the cap to 64. Collect (combo, model, elapsed, status).
  4. Checkpoint after every clique to /tmp/native_enum.json (never lost on
     timeout kill).

Output rows per combo: clique_idx | combo_idx | status (sat/unsat/unknown) |
elapsed_ms | node_constraint | model (concrete values) | source_location.

Usage: python3 _native_enum.py   (run under `timeout`)
"""
import json
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, "/home/dev/project/src")

from concolic_engine.coverage import (          # noqa: E402
    CoverageChecker,
    _maximal_cliques,
    _outcome_constraint,
    _block_constraint,
    _combo_constraint,
)
from concolic_engine.run import Run              # noqa: E402
from concolic_engine.solver import check_satisfiability  # noqa: E402
import coverage_assumptions                      # noqa: E402

PER_CLIQUE_BUDGET_S = float(os.environ.get("PER_CLIQUE_BUDGET_S", "120"))
CAP_PER_CLIQUE = int(os.environ.get("CAP_PER_CLIQUE", "64"))
CHECKPOINT = "/tmp/native_enum.json"
CHECKPOINT_EVERY = int(os.environ.get("CHECKPOINT_EVERY", "1"))  # cliques

# Reuse the checker's own timeout_ms (same as bounded run: 5000).
TIMEOUT_MS = 5000


def load_runs(here):
    """Same corpus as the bounded run: all dump_*.json EXCEPT replay evidence
    dumps (the replay dumps are generated by us, not part of the 4984 corpus).
    Applies the same fix_len_names rename as _run_coverage_check.py."""
    _LEN_RE = re.compile(r"len\(([^()]+)\)")

    def fix_len_names(dump):
        return json.loads(_LEN_RE.sub(r"SYM_LEN_\1", json.dumps(dump)))

    runs = []
    skipped = []
    for f in sorted(os.listdir(here)):
        if not (f.startswith("dump_") and f.endswith(".json")):
            continue
        if "replay" in f:
            continue  # exclude our own evidence dumps
        try:
            raw = json.load(open(os.path.join(here, f)))
            runs.append(Run.from_dict(fix_len_names(raw)))
        except Exception as e:  # noqa: BLE001
            skipped.append((f, type(e).__name__))
    return runs, skipped


def main() -> int:
    runs, skipped = load_runs(HERE)
    print(f"loaded {len(runs)} runs ({len(skipped)} unparseable)", flush=True)

    assumptions = coverage_assumptions.build()
    cc = CoverageChecker(runs, assumptions=assumptions, timeout_ms=TIMEOUT_MS)
    print(f"assumptions: {len(assumptions.assumptions)} total", flush=True)

    # ---- steps 1-3 (native) --------------------------------------------
    decls = cc._merged_declarations()
    bounds = cc._merged_bounds()
    extra = assumptions.symbolic_constraints()
    fixed_base = list(extra) + bounds

    expr_order, expr_source, expr_location, run_outcomes = [], {}, {}, []
    for run in cc.runs:
        outcomes = {}
        for pc in run.path_conditions:
            if pc.expr not in expr_source:
                expr_order.append(pc.expr)
                expr_source[pc.expr] = pc.source
                expr_location[pc.expr] = pc.source_location
            outcomes.setdefault(pc.expr, set()).add(bool(pc.taken))
        if outcomes:
            run_outcomes.append(outcomes)

    # parseability probe (native) — filters out unparseable exprs so they
    # can NEVER masquerade as UNSAT later.
    parseable, unevaluable = [], []
    for expr in expr_order:
        probe = check_satisfiability([f"Or({expr}, Not({expr}))"], decls, TIMEOUT_MS)
        if probe.satisfiable:
            parseable.append(expr)
        else:
            unevaluable.append(expr)

    # ---- step 4: assumption filtering (native) -------------------------
    from concolic_engine.assumptions import PathSource
    untracked_exprs, pinned, active = [], {}, []
    for expr in parseable:
        src = expr_source[expr]
        if assumptions.is_untracked(src, expr):
            untracked_exprs.append(expr)
            continue
        for side, outcome in (("taken", True), ("not_taken", False)):
            if assumptions.is_one_side_untracked(src, side, expr):
                pinned[expr] = not outcome
        active.append(expr)

    # ---- step 5: dependence graph + maximal cliques --------------------
    adj = {e: set() for e in active}
    for i, ea in enumerate(active):
        for eb in active[i + 1:]:
            if assumptions.are_independent(expr_source[ea], expr_source[eb], ea, eb):
                continue
            adj[ea].add(eb)
            adj[eb].add(ea)
    cliques = _maximal_cliques(active, adj, cap=1024)
    if cliques is None:
        cliques = [[e] for e in active]
        truncated = True
    else:
        truncated = False
    print(f"exprs: {len(active)} active, {len(unevaluable)} unevaluable, "
          f"{len(cliques)} cliques", flush=True)

    # ---- step 6: per-clique enumeration (raised cap, budget) -----------
    all_rows = []
    t_start = time.time()
    for ci, clique in enumerate(cliques):
        clique = sorted(clique, key=expr_order.index)
        c_start = time.time()
        fixed = list(fixed_base)
        for expr in clique:
            if expr in pinned:
                fixed.append(_outcome_constraint(expr, pinned[expr]))

        blocks: list = []
        space_covered = False
        for outcomes in run_outcomes:
            if not all(outcomes.get(e) for e in clique):
                continue
            fixed_outcomes = [
                (e, next(iter(outcomes[e])))
                for e in clique
                if len(outcomes[e]) == 1
            ]
            if not fixed_outcomes:
                space_covered = True
                break
            blocks.append(_block_constraint(fixed_outcomes))
        if space_covered:
            print(f"clique {ci:2d}/{len(cliques)}: SPACE COVERED (skip)", flush=True)
            continue

        found = 0
        timed_out = False
        while (not timed_out) and found < CAP_PER_CLIQUE:
            # per-clique wall-clock budget check BEFORE each combo
            if time.time() - c_start > PER_CLIQUE_BUDGET_S:
                timed_out = True
                break
            combo, model, elapsed, status = cc._next_untried_combo(
                clique, fixed, blocks, decls
            )
            if status == "unknown":
                timed_out = True
                break
            if combo is None:  # native UNSAT: clique space exhausted
                break
            blocks.append(_block_constraint(combo))
            found += 1
            row = {
                "clique_idx": ci,
                "combo_idx": found,
                "status": status,
                "elapsed_ms": round(elapsed, 1),
                "node_constraint": " AND ".join(
                    _outcome_constraint(e, o) for e, o in combo
                ),
                "source_location": (
                    expr_location[clique[0]] if len(clique) == 1 else ""
                ),
                "model": model or {},
            }
            all_rows.append(row)
            print(f"  clique {ci:2d} combo {found:2d} [{status:5s}] "
                  f"{elapsed:7.1f}ms  {row['node_constraint'][:80]}", flush=True)

        if (ci + 1) % CHECKPOINT_EVERY == 0 or (ci + 1) == len(cliques):
            _checkpoint(all_rows)
        print(f"clique {ci}/{len(cliques)} done: {found} combos "
              f"{'TIMED-OUT' if timed_out else ''}", flush=True)

    _checkpoint(all_rows)
    wall = time.time() - t_start
    summary = {
        "wall_seconds": round(wall, 1),
        "total_combos": len(all_rows),
        "by_status": {},
        "cliques": len(cliques),
        "truncated": truncated,
        "unevaluable": len(unevaluable),
    }
    for r in all_rows:
        summary["by_status"][r["status"]] = summary["by_status"].get(r["status"], 0) + 1
    with open(CHECKPOINT + ".summary", "w") as fh:
        json.dump(summary, fh, indent=2)
    print("\n=== SUMMARY ===")
    print(f"wall={summary['wall_seconds']}s  combos={summary['total_combos']}  "
          f"by_status={summary['by_status']}  cliques={summary['cliques']}  "
          f"truncated={summary['truncated']}")
    print(f"wrote {CHECKPOINT} (+ .summary)")
    return 0


def _checkpoint(rows):
    with open(CHECKPOINT, "w") as fh:
        json.dump({"rows": rows}, fh, indent=2)
    print(f"  [checkpoint] {len(rows)} combos -> {CHECKPOINT}", flush=True)


if __name__ == "__main__":
    sys.exit(main())