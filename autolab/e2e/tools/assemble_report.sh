#!/usr/bin/env bash
# assemble_report.sh — REPORT.md = generated numbers + hand-written prose.
# Every figure comes from tools/report.py reading INVENTORY.json, so nothing
# in the prose is hand-typed and nothing can drift from the artifacts.
set -euo pipefail
cd "$(dirname "$0")/.."
PY=/home/dev/project/venvs/queries_from_runs/bin/python3
LABEL="${1:-round 2 (after the repairs)}"
INV="${2:-INVENTORY}"

{
  sed -n '1,/^---$/p' REPORT_PROSE.md | head -n -1
  echo
  echo "---"
  echo
  echo "# The numbers"
  echo
  echo "<!-- generated by tools/report.py; do not hand-edit -->"
  echo
  "$PY" tools/report.py "${INV}.json" "${INV}_RANKED.json" "$LABEL"
  echo
  sed -n '/^---$/,$p' REPORT_PROSE.md | tail -n +2
} > REPORT.md
echo "wrote REPORT.md ($(wc -l < REPORT.md) lines)"
